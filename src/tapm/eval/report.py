def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _fix(r: dict) -> str:
    n = int(r.get("rem_paths") or 0)
    if not n:
        return "–"
    return f"{r['rem_break']}/{n} break" + (f", {r['rem_downgrade_only']} downgrade" if int(r["rem_downgrade_only"] or 0) else "")


def compute_labeling_status(root: Path = PROJECT_ROOT) -> dict:
    """Who labeled the gold files: labeled pairs per suite, and what each file's header says about Reviewer 2.

    One person (the engine's author) wrote every label. No second person has labeled a gold file, so no agreement
    statistic is computed. A28 retracted the A27 agreement figures, which compared Reviewer 1's labels with a copy
    of themselves in which three entries had been changed by hand.
    """
    import re

    import yaml

    heldout = {c["id"] for c in yaml.safe_load(
        (root / "evaluations/tier2/manifest-heldout.yaml").read_text(encoding="utf-8"))["cases"]}
    suites = {
        "tier2": {"label": "Tier-2 (CloudGoat + IAM-Vulnerable)", "files": 0, "pairs": 0, "pending": 0, "unrecorded": 0},
        "heldout": {"label": "Held-out (CloudGoat blind, E4)", "files": 0, "pairs": 0, "pending": 0, "unrecorded": 0},
        "benign": {"label": "Benign (real-world modules, E6)", "files": 0, "pairs": 0, "pending": 0, "unrecorded": 0},
    }
    gold = [(p, None) for p in sorted((root / "evaluations/tier2/gold").glob("*.yaml"))]
    gold += [(p, "benign") for p in sorted((root / "evaluations/realworld/gold").glob("*.yaml"))]
    for p, key in gold:
        text = p.read_text(encoding="utf-8")
        data = yaml.safe_load(text)
        key = key or ("heldout" if data.get("case") in heldout else "tier2")
        s = suites[key]
        s["files"] += 1
        s["pairs"] += len(data.get("expected") or [])
        if re.search(r"reviewer[ _]2:\s*pending", text, re.IGNORECASE):
            s["pending"] += 1
        elif not re.search(r"reviewer[ _]2", text, re.IGNORECASE):
            s["unrecorded"] += 1
        else:
            raise ValueError(f"{p.name}: Reviewer 2 field is neither PENDING nor absent; update compute_labeling_status")
    total = {k: sum(s[k] for s in suites.values()) for k in ("files", "pairs", "pending", "unrecorded")}
    return {"suites": suites, "total": total}


