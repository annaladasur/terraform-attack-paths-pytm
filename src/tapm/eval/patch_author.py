"""Evaluation runner for automated patch proposal generation on local model (Task E8 / Slide 13 / Plan §18-19).

Measures automated patch proposals generated by a real model (qwen3-coder:30b via Ollama or recorded):
1. Proposal re-planning: multi-attempt loop where rejection/downgrade feedback is fed back to the model.
2. Edit policy: proposals checked deterministically before execution (confined to cited blocks, no new blocks/suppressions).
3. Verification: proposals applied to isolated copies, re-planned offline, re-analyzed via PyTM and path engine.
4. Accepted / rejected metrics: proven breaks, proven downgrades, policy rejections, verifier rejections.
5. Latencies and costs: per-proposal generation latency (p50 / p95) and cost ($0.0 local).
6. Statistical intervals: Wilson 95% score confidence intervals for all binomial rates.
7. Provenance: git SHAs, tool versions, command line, tag, gold hashes.
"""

from __future__ import annotations

import json
import os
import statistics
import sys
import time
from pathlib import Path
from typing import Any, Callable

from ..ai.llm import AnthropicLLM, CassetteLLM, OllamaLLM, OpenAILLM, SimulatedLLM
from ..ai.remediate import remediate_path
from ..cli import FIXTURES, ensure_plan, fixture_config, resolve_fixture
from ..pipeline import run_deterministic
from ..util import PROJECT_ROOT, dump_json
from .metadata import get_eval_metadata
from .stats import format_rate_with_ci, wilson_interval

CANONICAL_FIXTURES = [
    "006-public-workload-iam-sensitive-bucket",
    "002-public-s3",
    "013-count",
]


class NeedsRealModel(RuntimeError):
    pass


def make_patch_author_llm(ai_cfg: dict, run_tag: str, seed: int | None = None):
    kind = ai_cfg.get("llm", "ollama")
    cassettes = ai_cfg.get("cassette_dir", "cassettes")
    if kind in ("simulated", "scripted", "off"):
        if ai_cfg.get("allow_simulated"):
            return SimulatedLLM()
        raise NeedsRealModel(
            "the patch author evaluation measures proposal generation on a real model; "
            "use --llm ollama|anthropic|openai or --llm recorded to replay them"
        )
    if kind == "recorded":
        return CassetteLLM(cassettes, run_tag=run_tag)
    if kind == "ollama":
        model = ai_cfg.get("model") or os.environ.get("TAPM_OLLAMA_MODEL", "qwen3-coder:30b")
        inner = OllamaLLM(model=model, num_ctx=ai_cfg.get("num_ctx"), seed=seed)
    elif kind in ("anthropic", "openai"):
        inner = {"anthropic": AnthropicLLM, "openai": OpenAILLM}[kind](ai_cfg.get("model"))
    else:
        raise ValueError(f"unknown or unsupported LLM backend: '{kind}'")
    return CassetteLLM(cassettes, inner=inner, run_tag=run_tag) if ai_cfg.get("record") else inner


def run_patch_author_eval(
    fixtures: list[Path | str] | None = None,
    ai_cfg: dict | None = None,
    max_attempts: int = 3,
    out_dir: Path | str | None = None,
    write_results: bool = False,
    tag: str = "local",
    command: str = "",
    write_cache: bool = True,
    llm_factory: Callable[[int, int], Any] | None = None,
) -> dict[str, Any]:
    if ai_cfg is None:
        ai_cfg = {"llm": "ollama", "model": "qwen3-coder:30b"}
    else:
        ai_cfg = dict(ai_cfg)

    # Resolve fixture paths
    if not fixtures:
        fixtures = [FIXTURES / name for name in CANONICAL_FIXTURES]
    resolved_fixtures: list[Path] = []
    for f in fixtures:
        p = Path(f) if isinstance(f, (str, Path)) else f
        resolved_fixtures.append(resolve_fixture(str(p)))

    gold_files: list[Path] = []
    for fx in resolved_fixtures:
        g = fx / "gold.yaml"
        if g.exists():
            gold_files.append(g)

    metadata_doc = get_eval_metadata(
        command=command or " ".join(sys.argv),
        tag=tag,
        gold_files=gold_files,
    )

    per_fixture: dict[str, Any] = {}
    all_path_results: list[dict[str, Any]] = []
    all_latencies: list[int] = []

    total_attempts = 0
    re_planned_proposals = 0
    edit_policy_rejected = 0
    verification_rejected = 0
    unverified_proposals = 0
    accepted_proposals = 0
    re_planning_progressions = 0

    run_seed = ai_cfg.get("seed", 42)

    for fx_idx, fx in enumerate(resolved_fixtures):
        ensure_plan(fx, quiet=True)
        res = run_deterministic(fixture_config(fx, None, no_dfd=True))
        if not res.paths:
            continue

        fx_paths: list[dict[str, Any]] = []
        for path_idx, path in enumerate(res.paths):
            if llm_factory is not None:
                llm = llm_factory(fx_idx, path_idx)
            else:
                llm = make_patch_author_llm(ai_cfg, f"{fx.name}-{path.id}", seed=run_seed)

            t0 = time.monotonic()
            path_rem = remediate_path(res, path, llm, max_attempts=max_attempts, write_cache=write_cache)
            duration_ms = int((time.monotonic() - t0) * 1000)

            attempts = path_rem.get("attempts", [])
            total_attempts += len(attempts)

            # Check progression (e.g. attempt 1 rejected/downgraded and subsequent attempt broke or improved)
            if len(attempts) > 1:
                first_st = attempts[0].get("status")
                best_st = path_rem.get("result")
                if first_st in ("REJECTED", "PROVEN_DOWNGRADE") and best_st == "PROVEN_BREAK":
                    re_planning_progressions += 1

            for a in attempts:
                lat = a.get("latency_ms")
                if lat:
                    all_latencies.append(lat)
                st = a.get("status")
                stage = a.get("stage")
                if stage == "edit policy" or (st == "REJECTED" and stage != "verification"):
                    edit_policy_rejected += 1
                elif stage == "verification" and st == "REJECTED":
                    verification_rejected += 1
                elif st == "UNVERIFIED":
                    unverified_proposals += 1

                if a.get("stage") == "verification":
                    re_planned_proposals += 1

                if st in ("PROVEN_BREAK", "PROVEN_DOWNGRADE", "ROUTE_BROKEN"):
                    accepted_proposals += 1

            path_record = {
                "fixture": fx.name,
                "path": path.id,
                "priority": path.priority,
                "nodes": path.nodes,
                "duration_ms": duration_ms,
                "result": path_rem.get("result"),
                "recommended_attempt": path_rem.get("recommended_attempt"),
                "recommended_diff": path_rem.get("recommended_diff"),
                "attempts": attempts,
            }
            fx_paths.append(path_record)
            all_path_results.append(path_record)

        per_fixture[fx.name] = {
            "fixture": fx.name,
            "paths_count": len(fx_paths),
            "paths": fx_paths,
        }

    paths_count = len(all_path_results)
    verified_break_count = sum(1 for p in all_path_results if p["result"] == "PROVEN_BREAK")
    verified_downgrade_count = sum(1 for p in all_path_results if p["result"] in ("PROVEN_DOWNGRADE", "ROUTE_BROKEN"))
    no_fix_count = sum(1 for p in all_path_results if p["result"] == "NO_VERIFIED_FIX")

    lat_sorted = sorted(all_latencies) if all_latencies else [0]
    p50_lat = statistics.median(lat_sorted) if lat_sorted else 0.0
    p95_lat = lat_sorted[min(len(lat_sorted) - 1, int(round(0.95 * (len(lat_sorted) - 1))))] if lat_sorted else 0.0
    mean_lat = round(statistics.mean(lat_sorted), 1) if lat_sorted else 0.0

    summary = {
        "fixtures_count": len(resolved_fixtures),
        "paths_attempted": paths_count,
        "verified_break": verified_break_count,
        "verified_break_rate": format_rate_with_ci(verified_break_count, paths_count),
        "verified_break_wilson_95": list(wilson_interval(verified_break_count, paths_count, 0.95)) if paths_count else None,
        "verified_downgrade_only": verified_downgrade_count,
        "verified_downgrade_rate": format_rate_with_ci(verified_downgrade_count, paths_count),
        "no_verified_fix": no_fix_count,
        "no_verified_fix_rate": format_rate_with_ci(no_fix_count, paths_count),
        "attempts_total": total_attempts,
        "re_planned_proposals": re_planned_proposals,
        "re_plan_rate": format_rate_with_ci(re_planned_proposals, total_attempts),
        "re_plan_rate_wilson_95": list(wilson_interval(re_planned_proposals, total_attempts, 0.95)) if total_attempts else None,
        "accepted_proposals": accepted_proposals,
        "acceptance_rate": format_rate_with_ci(accepted_proposals, total_attempts),
        "acceptance_rate_wilson_95": list(wilson_interval(accepted_proposals, total_attempts, 0.95)) if total_attempts else None,
        "edit_policy_rejected": edit_policy_rejected,
        "verification_rejected": verification_rejected,
        "unverified": unverified_proposals,
        "re_planning_progressions": re_planning_progressions,
        "latency_ms": {
            "p50": float(p50_lat),
            "p95": float(p95_lat),
            "mean": float(mean_lat),
            "min": min(lat_sorted) if lat_sorted else 0,
            "max": max(lat_sorted) if lat_sorted else 0,
        },
        "cost_usd": 0.0,
    }

    out: dict[str, Any] = {
        "backend": ai_cfg.get("llm", "ollama"),
        "model": ai_cfg.get("model", "qwen3-coder:30b"),
        "tag": tag,
        "command": command or " ".join(sys.argv),
        "git_sha": metadata_doc.get("git_sha", {}),
        "tool_versions": metadata_doc.get("tool_versions", {}),
        "metadata": metadata_doc,
        "canonical_fixtures": [fx.name for fx in resolved_fixtures],
        "summary": summary,
        "per_fixture": per_fixture,
    }

    if write_results:
        target_dir = Path(out_dir) if out_dir else PROJECT_ROOT / "evaluations" / "results"
        target_file = target_dir / f"patch-author-{tag}.json"
    elif out_dir:
        target_dir = Path(out_dir)
        target_file = target_dir / f"patch-author-{tag}.json"
    else:
        target_dir = PROJECT_ROOT / "artifacts" / "patch-author"
        target_file = target_dir / f"patch-author-{tag}.json"

    target_dir.mkdir(parents=True, exist_ok=True)
    dump_json(out, target_file)

    md_report = render_patch_author_markdown(out)
    md_file = target_dir / f"patch-author-{tag}.md"
    md_file.write_text(md_report, encoding="utf-8")

    out["out_file"] = str(target_file)
    return out


def render_patch_author_markdown(out: dict[str, Any]) -> str:
    s = out["summary"]
    lat = s["latency_ms"]
    fixtures_str = ", ".join(f"`{f}`" for f in out.get("canonical_fixtures", []))

    lines = [
        "# Automated Patch Author Evaluation (Local Model)",
        "",
        f"- **Backend:** `{out['backend']}`" + (f", model `{out['model']}`" if out.get("model") else ""),
        f"- **Canonical Fixtures Evaluated ({s['fixtures_count']}):** {fixtures_str}",
        f"- **Paths Attempted:** {s['paths_attempted']}",
        f"- **Verified Fix (Breaks Path):** {s['verified_break']} ({s['verified_break_rate']})",
        f"- **Verified Downgrade Only:** {s['verified_downgrade_only']} ({s['verified_downgrade_rate']})",
        f"- **No Verified Fix:** {s['no_verified_fix']} ({s['no_verified_fix_rate']})",
        f"- **Proposals Attempted:** {s['attempts_total']}",
        f"- **Proposals Re-planned Offline:** {s['re_planned_proposals']} ({s['re_plan_rate']})",
        f"- **Proposals Accepted (Proven):** {s['accepted_proposals']} ({s['acceptance_rate']})",
        f"- **Rejections by Edit Policy:** {s['edit_policy_rejected']}",
        f"- **Rejections by Verifier:** {s['verification_rejected']}",
        f"- **Unverified Proposals:** {s['unverified']}",
        f"- **Re-planning Progressions:** {s['re_planning_progressions']} paths successfully adapted across attempts",
        f"- **Per-Proposal Latency:** p50 `{lat['p50']} ms`, p95 `{lat['p95']} ms` (mean `{lat['mean']} ms`)",
        f"- **Cost:** `${s['cost_usd']:.2f}` (local model)",
        "",
        "## Evaluated Paths and Proposed Patches",
        "",
        "| Fixture | Path | Target Resource | Result | Recommended Attempt | Attempts |",
        "|---|---|---|---|---|---|",
    ]

    for fx_name, fx_data in out.get("per_fixture", {}).items():
        for p in fx_data.get("paths", []):
            target = p["nodes"][-1] if p["nodes"] else "unknown"
            rec = f"Attempt {p['recommended_attempt']}" if p.get("recommended_attempt") else "—"
            lines.append(
                f"| `{fx_name}` | `{p['path']}` | `{target}` | `{p['result']}` | {rec} | {len(p['attempts'])} |"
            )

    lines += [
        "",
        "### Attempt Details & Re-Planning",
        "",
    ]

    for fx_name, fx_data in out.get("per_fixture", {}).items():
        for p in fx_data.get("paths", []):
            lines.append(f"#### `{fx_name}` — `{p['path']}` ({p['priority'].upper()})")
            for a in p.get("attempts", []):
                pt = a.get("patch", {})
                hop = pt.get("hop", "?")
                f = pt.get("file", "?")
                st = a.get("status", "UNKNOWN")
                stage = f" ({a['stage']})" if a.get("stage") else ""
                reasons = "; ".join(a.get("reasons", [])) if a.get("reasons") else "none"
                lines.append(
                    f"- **Attempt {a['n']} (hop {hop}, `{f}`):** status `{st}`{stage} · reasons: {reasons}"
                )
                if a.get("effect"):
                    lines.append(f"  - Verified effect: `{a['effect']}` (re-planned offline: `{a.get('plan_source', 'cache')}`)")
            lines.append("")

    lines += [
        "> Addresses Slide 13 claim (Claims audit #38): The model proposes patch candidates; "
        "the deterministic edit policy bounds the syntax, and offline re-planning deterministically proves the security effect. "
        "No proposed patch is ever automatically applied to the repository without human review.",
        "",
    ]
    return "\n".join(lines)
